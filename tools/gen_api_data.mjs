// Writes api/_products.js (plain JS) from src/data/catalog.json so the Vercel
// functions don't import JSON. Files starting with "_" in api/ are not routes.
// Run after editing the catalog: node tools/gen_api_data.mjs
import { readFileSync, writeFileSync } from "node:fs";
const { products } = JSON.parse(readFileSync(new URL("../src/data/catalog.json", import.meta.url), "utf8"));
const slim = products.map(({ id, name, type, color, price, looks, looksPartial }) =>
  ({ id, name, type, color, price, looks: looks ?? 0, looksPartial: !!looksPartial }));
const { colors } = JSON.parse(readFileSync(new URL("../src/data/colors.json", import.meta.url), "utf8"));
// same as colorSlug() in src/catalog.ts: "Verde Militar" -> "verde-militar"
const slug = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
writeFileSync(
  new URL("../api/_products.js", import.meta.url),
  `// Generated by tools/gen_api_data.mjs from src/data/catalog.json + colors.json. Do not edit.\n` +
    `export const PRODUCTS = ${JSON.stringify(slim, null, 1)};\n` +
    `export const COLORS = ${JSON.stringify(colors.map((c) => c.name))};\n` +
    `export const COLOR_HEX = ${JSON.stringify(colors.map((c) => c.hex))};\n` +
    `export const COLOR_SLUG = ${JSON.stringify(colors.map((c) => slug(c.name)))};\n`,
);
console.log(slim.length, "products");
