// Writes api/_products.js (plain JS) from src/data/catalog.json so the Vercel
// functions don't import JSON. Files starting with "_" in api/ are not routes.
// Run after editing the catalog: node tools/gen_api_data.mjs
import { readFileSync, writeFileSync } from "node:fs";
const { products } = JSON.parse(readFileSync(new URL("../src/data/catalog.json", import.meta.url), "utf8"));
const slim = products.map(({ id, name, type, color }) => ({ id, name, type, color }));
writeFileSync(
  new URL("../api/_products.js", import.meta.url),
  `// Generated by tools/gen_api_data.mjs from src/data/catalog.json. Do not edit.\nexport const PRODUCTS = ${JSON.stringify(slim, null, 1)};\n`,
);
console.log(slim.length, "products");
