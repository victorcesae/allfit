"""Link-preview assets from the studio looks (WhatsApp / Instagram / Facebook, 1200x630).

Writes, from src/data/catalog.json + colors.json and public/products/<id>-l0.webp:
  public/og/<id>.jpg           product card in the photographed colour (static, also the fallback)
  public/og/base/<id>.png      the same card without the look and the colour line: api/og-image.js
                               paints the look in another palette colour and composes it on top
  public/og/thumb/<id>.jpg     400x500 look for the shared-bag collage (api/bag-image.js)
  public/og/label/color-<i>.png  palette colour names (the server has no fonts)
  api/_og_layout.js            where api/og-image.js puts the look, the colour dot and its name
Products whose look shows only part of the piece (looksPartial) keep their mannequin photo.
Usage: python tools/og_looks.py   (then python tools/og_store.py for the store card)
"""
import json, os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)
W, H = 1200, 630
CREAM = (247, 240, 237)                      # the looks' own backdrop: the card continues it
PLUM, ROSE, MUTED = (58, 29, 43), (192, 61, 114), (106, 74, 88)
FR = P("node_modules/@fontsource/fraunces/files/fraunces-latin-600-normal.woff2")
DM = P("node_modules/@fontsource-variable/dm-sans/files/dm-sans-latin-wght-normal.woff2")
cat = json.load(open(P("src/data/catalog.json"), encoding="utf8"))["products"]
colors = json.load(open(P("src/data/colors.json"), encoding="utf8"))["colors"]
logo = Image.open(P("public/logo.png")).convert("RGBA")
logo = logo.resize((round(logo.width * 96 / logo.height), 96), Image.LANCZOS)
for d in ("og", "og/base", "og/thumb", "og/label"):
    os.makedirs(P("public", d), exist_ok=True)
f_meta = ImageFont.truetype(DM, 28)


def wrap(d, text, font, width):
    lines, cur = [], ""
    for w in text.split():
        t = (cur + " " + w).strip()
        if d.textlength(t, font=font) <= width: cur = t
        else: lines.append(cur); cur = w
    return lines + [cur]


def look_of(p):
    if p.get("looks") and not p.get("looksPartial"):
        return Image.open(P("public/products", f"{p['id']}-l0.webp")).convert("RGB")
    return Image.open(P("public/products", f"{p['id']}-0.webp")).convert("RGB")


layout = {}
for p in cat:
    photo = look_of(p)
    ph = H; pw = round(photo.width * ph / photo.height)
    px = W - pw - 40
    base = Image.new("RGB", (W, H), CREAM)
    d = ImageDraw.Draw(base)
    base.paste(logo, (70, 60), logo)
    for size in (54, 46, 40, 34):                     # largest size that keeps the name on 2 lines
        f_name = ImageFont.truetype(FR, size)
        lines = wrap(d, p["name"], f_name, px - 140)
        if len(lines) <= 2: break
    y = 210
    for line in lines[:2]:
        d.text((72, y), line, font=f_name, fill=PLUM); y += int(size * 1.22)
    y += 14
    color_y = y                                         # the colour line goes here
    y += 48
    d.text((74, y), f"R$ {p['price']}", font=ImageFont.truetype(FR, 46), fill=PLUM); y += 64
    d.text((74, y), "Peça pelo WhatsApp", font=f_meta, fill=ROSE)
    d.text((74, H - 70), "useallfit.vercel.app", font=ImageFont.truetype(DM, 24), fill=MUTED)
    base.save(P("public/og/base", f"{p['id']}.png"), optimize=True)
    # static card: base + look + photographed colour
    card = base.copy(); d = ImageDraw.Draw(card)
    card.paste(photo.resize((pw, ph), Image.LANCZOS), (px, 0))
    d.ellipse([74, color_y + 6, 96, color_y + 28], fill=p["hex"], outline=(0, 0, 0))
    d.text((110, color_y), p["color"], font=f_meta, fill=PLUM)
    card.save(P("public/og", f"{p['id']}.jpg"), quality=86, optimize=True, progressive=True)
    # bag collage tile (4:5)
    photo.resize((400, 500), Image.LANCZOS).save(P("public/og/thumb", f"{p['id']}.jpg"), quality=86, optimize=True)
    layout[p["id"]] = {"x": px, "w": pw, "colorY": color_y}

for i, c in enumerate(colors):
    probe = ImageDraw.Draw(Image.new("RGBA", (1, 1)))
    w = int(probe.textlength(c["name"], font=f_meta)) + 4
    lab = Image.new("RGBA", (w, 40), (0, 0, 0, 0))
    ImageDraw.Draw(lab).text((0, 0), c["name"], font=f_meta, fill=PLUM)
    lab.save(P("public/og/label", f"color-{i}.png"), optimize=True)

with open(P("api/_og_layout.js"), "w", encoding="utf8") as f:
    f.write("// Generated by tools/og_looks.py. Do not edit.\n"
            "// Product preview card: look at x (width w, full height), colour dot + name at colorY.\n"
            f"export const OG_LAYOUT = {json.dumps(layout)};\n")
print(len(cat), "cards,", len(colors), "colour labels")
